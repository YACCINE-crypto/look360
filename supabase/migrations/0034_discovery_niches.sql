-- ============================================================================
-- 0034 — Découverte automatique (mots-clés par niche × zone) + niches.
--
-- discovery_keywords : mots-clés que le système cherche lui-même, en rotation,
--   sur 3 zones (Afrique, Europe, Amérique), avec un budget quotidien.
--   Une recherche déjà faite récemment (par un utilisateur OU le système) est
--   réutilisée : pas de nouvel appel Apify.
-- Niches : chaque pub indexée reçoit la niche du mot-clé qui l'a trouvée ;
--   boutiques (niches[]) et produits (niche) en héritent → filtres par niche.
-- ============================================================================

create table if not exists public.discovery_keywords (
  id bigserial primary key,
  niche text not null,
  keyword text not null,
  zone text not null check (zone in ('africa', 'europe', 'america')),
  enabled boolean not null default true,
  runs integer not null default 0,
  last_run_at timestamptz,
  last_country text,
  last_count integer,
  last_source text,
  unique (keyword, zone)
);
alter table public.discovery_keywords enable row level security;
revoke all on public.discovery_keywords from anon, authenticated;
create index if not exists discovery_due_idx on public.discovery_keywords (enabled, last_run_at nulls first);

alter table public.shop_ad_links add column if not exists niche text;
alter table public.shops add column if not exists niches text[] not null default '{}';
alter table public.shop_products add column if not exists niche text;
create index if not exists shops_niches_idx on public.shops using gin (niches);

-- Niche d'une recherche (mot-clé de découverte, sinon niche du feed).
create or replace function public.niche_of(q text)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select niche from public.discovery_keywords where lower(keyword) = lower(trim(q)) limit 1),
    case lower(coalesce(q, ''))
      when 'voiture' then 'Automobile'
      when 'masseur' then 'Santé'
      when 'montre' then 'High-tech'
      when 'beauté' then 'Beauté'
      when 'cuisine' then 'Maison & cuisine'
      when 'ceinture' then 'Mode & accessoires'
      when 'bébé' then 'Bébé & enfant'
      when 'sport' then 'Sport & plein air'
      else null
    end
  );
$$;
revoke all on function public.niche_of(text) from public, anon, authenticated;
grant execute on function public.niche_of(text) to service_role;

create or replace function public.refresh_shop_index(p_days integer default 30)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_links integer;
  v_shops integer;
begin
  with src as (
    select e as ad, s.created_at as seen, public.niche_of(s.filters ->> 'q') as niche
    from public.spy_searches s,
         jsonb_array_elements(
           case jsonb_typeof(s.results) when 'array' then s.results
                else coalesce(s.results -> 'ads', '[]'::jsonb) end) e
    where s.created_at > now() - make_interval(days => p_days)
    union all
    select f.payload, f.refreshed_at,
           case f.niche when 'Auto & moto' then 'Automobile' when 'Bien-être' then 'Santé'
                        when 'Montre & tech' then 'High-tech' else f.niche end
    from public.feed_ads f
  ),
  norm as (
    select distinct on (ad ->> 'ad_archive_id')
      ad ->> 'ad_archive_id' as ad_archive_id,
      lower(regexp_replace(coalesce(ad ->> 'landing_domain', ''), '^www\.', '')) as domain,
      nullif(substring(ad ->> 'landing_url' from '/products/([A-Za-z0-9%._~-]+)'), '') as handle,
      ad as payload,
      coalesce((ad ->> 'is_active')::boolean, true) as is_active,
      nullif(ad ->> 'start_date', '')::date as start_date,
      ad ->> 'country' as country,
      nullif(ad ->> 'reach', '')::bigint as reach,
      niche,
      seen
    from src
    where coalesce(ad ->> 'landing_kind', '') = 'shop'
      and coalesce(ad ->> 'ad_archive_id', '') <> ''
    order by ad ->> 'ad_archive_id', (niche is null), seen desc
  ),
  up as (
    insert into public.shop_ad_links as l
      (ad_archive_id, domain, handle, payload, is_active, start_date, country, reach, niche, seen_at)
    select ad_archive_id, domain, lower(handle), payload, is_active, start_date, country, reach, niche, seen
    from norm
    where not public.is_non_shop_domain(domain)
    on conflict (ad_archive_id) do update set
      domain = excluded.domain, handle = excluded.handle, payload = excluded.payload,
      is_active = excluded.is_active, start_date = excluded.start_date,
      country = excluded.country, reach = excluded.reach,
      niche = coalesce(excluded.niche, l.niche),
      seen_at = greatest(l.seen_at, excluded.seen_at)
    returning 1
  )
  select count(*) into v_links from up;

  insert into public.shops (domain)
  select distinct domain from public.shop_ad_links
  on conflict (domain) do nothing;
  get diagnostics v_shops = row_count;

  update public.shops s set
    ads_count = a.n, ads_active = a.n_active, ad_countries = a.countries,
    eu_reach = a.reach, first_ad_date = a.first_ad, niches = a.niches
  from (
    select domain, count(*) as n, count(*) filter (where is_active) as n_active,
           array_remove(array_agg(distinct country), null) as countries,
           nullif(sum(reach), 0) as reach, min(start_date) as first_ad,
           array_remove(array_agg(distinct niche), null) as niches
    from public.shop_ad_links
    where seen_at > now() - make_interval(days => p_days)
    group by domain
  ) a
  where a.domain = s.domain;

  update public.shop_products p set
    ads_count = a.n, ads_active = a.n_active, first_ad_date = a.first_ad,
    eu_reach = a.reach, niche = coalesce(a.niche, p.niche)
  from (
    select l.domain, l.handle, count(*) as n, count(*) filter (where l.is_active) as n_active,
           min(l.start_date) as first_ad, nullif(sum(l.reach), 0) as reach,
           mode() within group (order by l.niche) filter (where l.niche is not null) as niche
    from public.shop_ad_links l
    where l.handle is not null and l.seen_at > now() - make_interval(days => p_days)
    group by l.domain, l.handle
  ) a, public.shops s
  where s.domain = a.domain and p.shop_id = s.id and lower(p.handle) = a.handle;

  return jsonb_build_object('links', v_links, 'new_shops', v_shops);
end;
$$;
revoke all on function public.refresh_shop_index(integer) from public, anon, authenticated;
grant execute on function public.refresh_shop_index(integer) to service_role;

